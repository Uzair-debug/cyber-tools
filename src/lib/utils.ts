import { clsx, type ClassValue } from 'clsx';
import { twMerge } from 'tailwind-merge';

export function cn(...inputs: ClassValue[]) {
  return twMerge(clsx(inputs));
}

/**
 * Formats one CSV cell: doubles quotes and wraps the value in quotes. Values starting with
 * =, +, -, @, tab or CR get a leading ' so spreadsheet apps don't run them as formulas
 * (CSV / formula injection from scanned or pasted data).
 */
export function csvCell(value: unknown): string {
  let text = value === null || value === undefined ? '' : String(value);
  if (/^[=+\-@\t\r]/.test(text)) text = `'${text}`;
  return `"${text.replace(/"/g, '""')}"`;
}
