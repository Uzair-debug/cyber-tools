// M365 & Entra PowerShell Script Catalog with Parameterized Code Generation

export interface ScriptParameter {
  id: string;
  label: string;
  type: 'text' | 'number' | 'boolean' | 'select';
  defaultValue: any;
  placeholder?: string;
  description: string;
  options?: string[];
}

export interface PowerShellScriptTemplate {
  id: string;
  title: string;
  category: 'Incident Response' | 'Identity & Roles' | 'Mailbox & Exchange' | 'Audit & Compliance' | 'OAuth & Apps';
  description: string;
  prerequisites: string[];
  requiredScopes: string[];
  parameters: ScriptParameter[];
  generateCode: (params: Record<string, any>) => string;
}

